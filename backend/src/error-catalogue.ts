// The one catalogue of machine-readable error codes (issue #115).
//
// Every HTTP error this API throws carries a code from here, and the code
// decides the status: `new HttpError('SLOT_TAKEN')` is a 409 because the
// catalogue says so. Keeping both in one entry is deliberate — a code that
// says 409 in the docs while the thrower sends 400 is exactly the drift this
// prevents.
//
// `message` is the default human-readable text for the code. Call sites may
// pass a more specific message, and (when a translation exists) the localized
// text for the code wins; `message` is kept in the envelope for backwards
// compatibility, so clients must branch on `code`, never on `message`.
//
// The generated catalogue page is `docs/api/error-catalogue.md`
// (`npm run errors:catalogue`); `npm run errors:check` fails CI when it is
// stale, and when any HttpError construction in src/ is uncoded.
export type ErrorModule =
  | 'shared'
  | 'auth'
  | 'users'
  | 'patients'
  | 'doctors'
  | 'availability'
  | 'appointments'
  | 'intake'
  | 'consultations'
  | 'referrals'
  | 'orders'
  | 'prescriptions'
  | 'lab-orders'
  | 'pharmacy-orders'
  | 'facilities'
  | 'payments'
  | 'notifications'
  | 'medications'
  | 'rate-limit'
  | 'audit'
  | 'flags'
  | 'metrics'
  | 'lab-tests';

export interface ErrorDefinition {
  /** HTTP status this code always answers with. */
  readonly status: number;
  /** Owning module, used to group the generated catalogue page. */
  readonly module: ErrorModule;
  /** Default public message. Call sites may override it; never branch on it. */
  readonly message: string;
  /** What the code means, for the catalogue page. */
  readonly meaning: string;
  /** What a client should do about it, for the catalogue page. */
  readonly guidance: string;
}

