// One-off local-dev helper: generates two fresh testnet Stellar keypairs
// (platform payer + releaser, see docs/adr/0004-custodial-payments-v1.md),
// funds them via Friendbot, and appends the secrets DIRECTLY to .env —
// never printed to stdout/logs. Only the public keys (safe to display)
// are printed. Delete this script's output and rerun for a fresh pair;
// never commit the resulting .env.
import { Keypair } from "@stellar/stellar-sdk";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = path.join(ROOT, ".env");

async function fund(publicKey) {
  const res = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(publicKey)}`);
  if (!res.ok) throw new Error(`Friendbot funding failed for ${publicKey}: ${res.status} ${await res.text()}`);
}

const payer = Keypair.random();
const releaser = Keypair.random();

await fund(payer.publicKey());
await fund(releaser.publicKey());

const lines = [
  "",
  "# Generated by scripts/gen-platform-identities.mjs — testnet only, never commit.",
  `PLATFORM_PAYER_SECRET=${payer.secret()}`,
  `PLATFORM_RELEASER_SECRET=${releaser.secret()}`,
  "",
].join("\n");

fs.appendFileSync(ENV_PATH, lines);

console.log("Funded and wrote secrets to .env (not printed here). Public keys:");
console.log("  payer:   ", payer.publicKey());
console.log("  releaser:", releaser.publicKey());
