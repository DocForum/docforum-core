// Generates fresh testnet payer/releaser identities. Locally, credentials
// are appended directly to .env; in Actions, they go to GITHUB_ENV and are
// masked. Secret values are never printed. See ADR 0004.
import { Keypair } from "@stellar/stellar-sdk";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = path.join(ROOT, ".env");

const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fund(publicKey) {
  const maxAttempts = 5;
  let lastFailure;
  let attempts = 0;
  for (let attempt = 0; attempt < maxAttempts; attempt += 1) {
    attempts = attempt + 1;
    try {
      const res = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(publicKey)}`);
      if (res.ok) return;
      lastFailure = `HTTP ${res.status}`;
      if (res.status !== 429 && res.status < 500) break;
    } catch (error) {
      lastFailure = error instanceof Error ? error.name : "network error";
    }
    if (attempt < maxAttempts - 1) {
      const backoff = Math.min(1000 * 2 ** attempt, 16_000);
      await wait(backoff + Math.floor(Math.random() * 500));
    }
  }
  throw new Error(`Friendbot funding failed for ${publicKey} after ${attempts} attempt(s) (${lastFailure}).`);
}

const payer = Keypair.random();
const releaser = Keypair.random();

await fund(payer.publicKey());
await fund(releaser.publicKey());

const envLines = [
  `PLATFORM_PAYER_SECRET=${payer.secret()}`,
  `PLATFORM_PAYER_PUBLIC_KEY=${payer.publicKey()}`,
  `PLATFORM_RELEASER_SECRET=${releaser.secret()}`,
  `PLATFORM_RELEASER_PUBLIC_KEY=${releaser.publicKey()}`,
].join("\n");

if (process.env.GITHUB_ENV) {
  process.stdout.write(`::add-mask::${payer.secret()}\n::add-mask::${releaser.secret()}\n`);
  fs.appendFileSync(process.env.GITHUB_ENV, `${envLines}\n`);
  console.log("Funded fresh testnet identities for this workflow run.");
} else {
  fs.appendFileSync(
    ENV_PATH,
    ["", "# Generated by scripts/gen-platform-identities.mjs — testnet only, never commit.", envLines, ""].join("\n"),
  );
  console.log("Funded and wrote secrets to .env (not printed here). Public keys:");
  console.log("  payer:   ", payer.publicKey());
  console.log("  releaser:", releaser.publicKey());
}
